// ==================================================
// HINA - AUTO REACTIONS
// ==================================================

module.exports = function autoReactions({
    api,
    event,
    isBotUser
}) {

    if (
        !event ||
        !api ||
        typeof isBotUser !== "function"
    ) {
        return;
    }

    // ==================================================
    // اختيار ضحكة عشوائية
    // ==================================================

    function randomLaughReaction() {

        return Math.random() < 0.5
            ? "😆"
            : "😹";

    }

    // ==================================================
    // التحقق من الكلمات
    // ==================================================

    function containsWord(
        text,
        words
    ) {

        return words.some(
            word =>
                text.includes(
                    String(word).toLowerCase()
                )
        );

    }

    // ==================================================
    // 😂 شخص تفاعل بضحكني على رسالة
    // ==================================================

    if (
        event.type === "message_reaction"
    ) {

        const reactorID =
            event.userID ||
            event.senderID ||
            event.authorID;

        // لا يتفاعل البوت مع نفسه
        if (
            reactorID &&
            isBotUser(reactorID)
        ) {
            return;
        }

        const reaction =
            event.reaction;

        /*
         * إذا كانت الضحكة 😂
         * البوت يضع نفس 😂
         *
         * وإذا كانت 😆 أو 😹
         * يضع نفس الإيموجي أيضًا
         */

        if (
            reaction === "😂" ||
            reaction === "😆" ||
            reaction === "😹" ||
            reaction === "🤣"
        ) {

            if (
                event.messageID &&
                typeof api.setMessageReaction ===
                    "function"
            ) {

                api.setMessageReaction(
                    reaction,
                    String(
                        event.messageID
                    ),
                    error => {

                        if (error) {

                            console.error(
                                "[HINA REACTION ERROR]",
                                error.message ||
                                error
                            );

                        }

                    },
                    true
                );

            }

        }

        return;
    }

    // ==================================================
    // يجب أن تكون رسالة
    // ==================================================

    if (
        event.type !== "message" ||
        !event.body ||
        !event.messageID
    ) {

        return;

    }

    // ==================================================
    // تجاهل البوت
    // ==================================================

    if (
        isBotUser(
            event.senderID
        )
    ) {

        return;

    }

    const text =
        String(
            event.body
        )
        .toLowerCase()
        .trim();

    let reaction =
        null;

    // ==================================================
    // 👑 توكا
    // ==================================================

    if (
        containsWord(
            text,
            [
                "توكا"
            ]
        )
    ) {

        reaction =
            "👑";

    }

    // ==================================================
    // 🧜🏻‍♀️ ريم
    // ==================================================

    if (
        !reaction &&
        containsWord(
            text,
            [
                "ريم"
            ]
        )
    ) {

        reaction =
            "🧜🏻‍♀️";

    }

    // ==================================================
    // 🌷 نوكا
    // ==================================================

    if (
        !reaction &&
        containsWord(
            text,
            [
                "نوكا"
            ]
        )
    ) {

        reaction =
            "🌷";

    }

    // ==================================================
    // 🐳 توشيرو
    // ==================================================

    if (
        !reaction &&
        containsWord(
            text,
            [
                "توشيرو"
            ]
        )
    ) {

        reaction =
            "🐳";

    }

    // ==================================================
    // 🦍 زاكي / اياتو / اياطو
    // ==================================================

    if (
        !reaction &&
        containsWord(
            text,
            [
                "زاكي",
                "اياتو",
                "اياطو"
            ]
        )
    ) {

        reaction =
            "🦍";

    }

    // ==================================================
    // 🦁 رضى
    // ==================================================

    if (
        !reaction &&
        containsWord(
            text,
            [
                "رضى"
            ]
        )
    ) {

        reaction =
            "🦁";

    }

    // ==================================================
    // 🐛 خالد
    // ==================================================

    if (
        !reaction &&
        containsWord(
            text,
            [
                "خالد"
            ]
        )
    ) {

        reaction =
            "🐛";

    }

    // ==================================================
    // 🪞 ايليوريث
    // ==================================================

    if (
        !reaction &&
        containsWord(
            text,
            [
                "ايليوريث"
            ]
        )
    ) {

        reaction =
            "🪞";

    }

    // ==================================================
    // 🦧 يوتا / شفق
    // ==================================================

    if (
        !reaction &&
        containsWord(
            text,
            [
                "يوتا",
                "شفق",
                "الشفق"
            ]
        )
    ) {

        reaction =
            "🦧";

    }

    // ==================================================
    // 🐈‍⬛ هريرة / أبو هريرة
    // ==================================================

    if (
        !reaction &&
        containsWord(
            text,
            [
                "هريرة",
                "ابو هريرة",
                "أبو هريرة"
            ]
        )
    ) {

        reaction =
            "🐈‍⬛";

    }

    // ==================================================
    // 🐇 أسماء / فردوس
    // ==================================================

    if (
        !reaction &&
        containsWord(
            text,
            [
                "أسماء",
                "اسماء",
                "فردوس",
                "أسماء فردوس"
            ]
        )
    ) {

        reaction =
            "🐇";

    }

    // ==================================================
    // 🦊 رؤى
    // ==================================================

    if (
        !reaction &&
        containsWord(
            text,
            [
                "رؤى",
                "ࢪؤى"
            ]
        )
    ) {

        reaction =
            "🦊";

    }

    // ==================================================
    // 🦋 فريال
    // ==================================================

    if (
        !reaction &&
        containsWord(
            text,
            [
                "فريال",
                "فࢪيال"
            ]
        )
    ) {

        reaction =
            "🦋";

    }

    // ==================================================
    // 👽 كايزر
    // ==================================================

    if (
        !reaction &&
        containsWord(
            text,
            [
                "كايزر",
                "كايزࢪ",
                "ڪايزر",
                "ڪايزࢪ"
            ]
        )
    ) {

        reaction =
            "👽";

    }

    // ==================================================
    // 🦌 نرجس
    // ==================================================

    if (
        !reaction &&
        containsWord(
            text,
            [
                "نرجس",
                "نࢪجس"
            ]
        )
    ) {

        reaction =
            "🦌";

    }

    // ==================================================
    // 🐧 جود
    // ==================================================

    if (
        !reaction &&
        containsWord(
            text,
            [
                "جود"
            ]
        )
    ) {

        reaction =
            "🐧";

    }

    // ==================================================
    // 🦔 يزن
    // ==================================================

    if (
        !reaction &&
        containsWord(
            text,
            [
                "يزن"
            ]
        )
    ) {

        reaction =
            "🦔";

    }

    // ==================================================
    // 😆 الضحك
    // ==================================================
    // هه
    // ههه
    // ههههه
    // ههههههههههههه
    // أي عدد من الهاء

    if (
        !reaction &&
        /ه{2,}/u.test(text)
    ) {

        reaction =
            randomLaughReaction();

    }

    // ==================================================
    // 😆 إيموجيات الضحك
    // ==================================================

    if (
        !reaction &&
        /😂|🤣|😹|😆/u.test(text)
    ) {

        reaction =
            randomLaughReaction();

    }

    // ==================================================
    // 😆 عبارات الضحك
    // ==================================================

    if (
        !reaction &&
        /متت|متتت|اموت|أموت|يموت ضحك|مت ضحك/u.test(text)
    ) {

        reaction =
            randomLaughReaction();

    }

    // ==================================================
    // 🤖 فيو
    // ==================================================

    if (
        text.includes("فيو") &&
        typeof api.sendMessage ===
            "function"
    ) {

        api.sendMessage(
            ".",
            event.threadID
        );

    }

    // ==================================================
    // تنفيذ التفاعل
    // ==================================================

    if (
        reaction &&
        typeof api.setMessageReaction ===
            "function"
    ) {

        api.setMessageReaction(
            reaction,
            String(
                event.messageID
            ),
            error => {

                if (error) {

                    console.error(
                        "[HINA REACTION ERROR]",
                        error.message ||
                        error
                    );

                }

            },
            true
        );

    }

};